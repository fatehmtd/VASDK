/// Random strings over [`CHAOS`] and random code points: inputs no tokenizer would produce,
/// which is the point.
fn chaos(per_set: usize, seed: u64) {
    let pool: Vec<char> = CHAOS.chars().collect();
    let mut out = std::io::stdout().lock();
    let mut rng = Rng(seed);
    for lang in ["en", "fr", "de", "es", "pt"] {
        for rules in ["default", "all", "none"] {
            for _ in 0..per_set {
                let n = 1 + rng.below(24);
                let text: String = (0..n)
                    .map(|_| match rng.below(10) {
                        0 => char::from_u32(rng.below(0x30000) as u32).unwrap_or('?'),
                        _ => pool[rng.below(pool.len())],
                    })
                    .collect();
                let expected = normalize_text(&text, parse_lang(lang), parse_rules(rules));
                let line = json!({"kind": "text", "lang": lang, "rules": rules, "text": text, "expected": expected});
                writeln!(out, "{line}").unwrap();
            }
        }
    }
    for _ in 0..per_set {
        let n = 1 + rng.below(12);
        let text: String = (0..n)
            .map(|_| match rng.below(3) {
                0 => char::from_u32(rng.below(0x30000) as u32).unwrap_or('?'),
                _ => pool[rng.below(pool.len())],
            })
            .collect();
        let (prepared, frames) = ptts::tts_model::prepare_text_prompt(&text);
        let line = json!({"kind": "prompt", "lang": "en", "rules": "none", "text": text, "expected": [prepared, frames]});
        writeln!(out, "{line}").unwrap();
    }
}

/// Paragraphs to plan: whole strings of the corpus strung together, so sentence grouping, the
/// 50-token limit and the 200-token cut all see realistic and adversarial input.
fn chunks(tokenizer: &str, corpus: &str, per_set: usize, seed: u64) {
    use ptts::Tokenizer as _;
    use ptts::plan;
    use ptts::preprocess::Normalize;
    let tok = ptts::tok::Tok::open(std::path::Path::new(tokenizer)).expect("tokenizer.json");
    let mut by_lang: std::collections::BTreeMap<String, Vec<String>> = Default::default();
    let file = std::fs::File::open(corpus).unwrap_or_else(|e| panic!("{corpus}: {e}"));
    for line in std::io::BufReader::new(file).lines() {
        let line = line.unwrap();
        if line.trim().is_empty() {
            continue;
        }
        let v: Value = serde_json::from_str(&line).unwrap();
        let (lang, text) = (v["lang"].as_str().unwrap(), v["text"].as_str().unwrap());
        let texts = by_lang.entry(lang.to_string()).or_default();
        if !texts.iter().any(|t| t == text) {
            texts.push(text.to_string());
        }
    }
    let mut out = std::io::stdout().lock();
    let mut rng = Rng(seed);
    let frame_rate = 12.5;
    let emit = |out: &mut std::io::StdoutLock, lang: &str, rules: &str, max_tokens: usize,
                    fit: Option<usize>, text: &str| {
        let normalize = match lang {
            "none" => Normalize::OFF,
            l => Normalize::for_lang(parse_lang(l)).with_rules(parse_rules(rules)),
        };
        let planned = plan::chunks(&tok, text, normalize, max_tokens, frame_rate).and_then(|c| match fit {
            Some(max) => plan::fit_or_error(c, max, &tok, frame_rate),
            None => Ok(c),
        });
        let expected = match planned {
            Ok(chunks) => Value::from(
                chunks
                    .iter()
                    .map(|c| {
                        json!({"text": c.text, "tokens": c.tokens, "frames_after_eos": c.frames_after_eos,
                               "frame_budget": c.frame_budget})
                    })
                    .collect::<Vec<_>>(),
            ),
            Err(e) => json!({"error": e.to_string()}),
        };
        let line = json!({"kind": "chunks", "lang": lang, "rules": rules, "max_tokens": max_tokens,
                          "fit": fit, "text": text, "expected": expected});
        writeln!(out, "{line}").unwrap();
    };
    const SEPS: &[&str] = &[" ", " ", " ", "\n", "  ", "\n\n", ""];
    const LIMITS: &[(usize, Option<usize>)] = &[
        (50, Some(200)),
        (50, Some(200)),
        (50, Some(200)),
        (20, Some(200)),
        (8, Some(30)),
        (120, Some(12)),
        (50, None),
    ];
    let pool: Vec<char> = CHAOS.chars().collect();
    for (lang, texts) in &by_lang {
        for rules in ["default", "all", "none"] {
            for _ in 0..per_set {
                // A reply of 1 to 24 corpus strings.
                let n = 1 + rng.below(24);
                let mut text = String::new();
                for i in 0..n {
                    if i > 0 {
                        text.push_str(SEPS[rng.below(SEPS.len())]);
                    }
                    text.push_str(&texts[rng.below(texts.len())]);
                }
                let (max_tokens, fit) = LIMITS[rng.below(LIMITS.len())];
                emit(&mut out, lang, rules, max_tokens, fit, &text);
            }
        }
        // One long sentence with no full stop: only fit can cut it, at a comma or a word.
        for _ in 0..per_set / 4 + 1 {
            let n = 40 + rng.below(400);
            let words: Vec<String> = (0..n)
                .map(|_| {
                    let mut w = rng.pick(TOKENS).to_string();
                    if rng.below(9) == 0 {
                        w.push_str(rng.pick(&[",", ";", ":", ",\"", ",»", ".", "?", "!"]));
                    }
                    w
                })
                .collect();
            let (max_tokens, fit) = LIMITS[rng.below(LIMITS.len())];
            emit(&mut out, lang, "default", max_tokens, fit, &words.join(" "));
        }
    }
    // Random strings, planned unnormalized (what a caller with normalization off sends).
    for _ in 0..per_set * 2 {
        let n = 1 + rng.below(60);
        let text: String = (0..n)
            .map(|_| match rng.below(8) {
                0 => char::from_u32(rng.below(0x30000) as u32).unwrap_or('?'),
                _ => pool[rng.below(pool.len())],
            })
            .collect();
        let (max_tokens, fit) = LIMITS[rng.below(LIMITS.len())];
        emit(&mut out, "none", "none", max_tokens, fit, &text);
    }
    // The tokenizer on its own, over every corpus string and random strings.
    let tokens = |out: &mut std::io::StdoutLock, text: &str| {
        let ids = tok.encode(text).expect("encode");
        writeln!(out, "{}", json!({"kind": "tokens", "text": text, "expected": ids})).unwrap();
    };
    for texts in by_lang.values() {
        for t in texts {
            tokens(&mut out, t);
        }
    }
    for _ in 0..per_set * 4 {
        let n = 1 + rng.below(30);
        let text: String = (0..n)
            .map(|_| match rng.below(4) {
                0 => char::from_u32(rng.below(0x30000) as u32).unwrap_or('?'),
                _ => pool[rng.below(pool.len())],
            })
            .collect();
        tokens(&mut out, &text);
    }
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    match args.get(1).map(String::as_str) {
        Some("unicode") => unicode(),
        Some("chaos") if args.len() == 4 => chaos(args[2].parse().expect("N"), args[3].parse().expect("SEED")),
        Some("chunks") if args.len() == 6 => chunks(
            &args[2],
            &args[3],
            args[4].parse().expect("N"),
            args[5].parse().expect("SEED"),
        ),
        Some("golden") if args.len() == 5 => {
            golden(&args[2], args[3].parse().expect("N"), args[4].parse().expect("SEED"))
        }
        _ => {
            eprintln!(
                "usage: phonon-normgen unicode | golden CORPUS.jsonl N SEED | chaos N SEED \
                 | chunks TOKENIZER.json CORPUS.jsonl N SEED"
            );
            std::process::exit(2);
        }
    }
}
