//! Reference data for VASDK's C++ port of the Phonon text normalizer (gradium-ai/xn-ptts
//! `ptts::preprocess`, v0.4.1).
//!
//!   phonon-normgen unicode                       > unicode_props.inc
//!   phonon-normgen golden CORPUS.jsonl N SEED    > normalize_golden.jsonl
//!   phonon-normgen chunks TOKENIZER.json CORPUS.jsonl N SEED > chunk_golden.jsonl
//!
//! `unicode` dumps the character properties the normalizer asks Rust's `char` about, as ranges,
//! so the C++ port classifies every code point exactly as the reference does.
//!
//! `golden` runs the reference on every case of CORPUS, one JSON object per line:
//!   {"kind": "text", "lang", "rules", "text"}  -> normalize_text(text, lang, rules)
//!   {"kind": "word", "lang", "rules", "text"}  -> rewrite_word(text, lang, rules), or null
//! then on N generated text cases per language and rule set, and prints each case with its
//! output added as "expected".
//!
//! `chunks` runs the reference's text planning (`ptts::plan::chunks`, then `fit_or_error`, as
//! `ptts::synth` does) with the checkpoint's own tokenizer.json, on paragraphs built from the
//! strings of CORPUS, long unpunctuated sentences and random strings:
//!   {"kind": "tokens", "text"}                                        -> encode(text)
//!   {"kind": "chunks", "lang", "rules", "max_tokens", "fit", "text"}  -> [{text, tokens,
//!                                                     frames_after_eos, frame_budget}] or {"error"}

use ptts::preprocess::{Lang, Rules, normalize_text, rewrite_word};
use serde_json::{Value, json};
use std::io::{BufRead, Write};

fn ranges(pred: impl Fn(char) -> bool) -> Vec<(u32, u32)> {
    let mut out: Vec<(u32, u32)> = vec![];
    for cp in 0..=0x10FFFFu32 {
        let Some(c) = char::from_u32(cp) else { continue };
        if !pred(c) {
            continue;
        }
        match out.last_mut() {
            Some((_, hi)) if *hi + 1 == cp => *hi = cp,
            _ => out.push((cp, cp)),
        }
    }
    out
}

fn emit_table(out: &mut impl Write, name: &str, table: &[(u32, u32)]) {
    writeln!(out, "static const CodeRange {name}[] = {{").unwrap();
    for chunk in table.chunks(6) {
        let row: Vec<String> = chunk.iter().map(|(lo, hi)| format!("{{0x{lo:X}, 0x{hi:X}}}")).collect();
        writeln!(out, "    {},", row.join(", ")).unwrap();
    }
    writeln!(out, "}};").unwrap();
}

fn unicode() {
    let mut out = std::io::stdout().lock();
    let (major, minor, update) = char::UNICODE_VERSION;
    writeln!(out, "// Generated by phonon-normgen from Rust's core::char (Unicode {major}.{minor}.{update}).").unwrap();
    writeln!(out, "// Do not edit: regenerate with `cargo run --release -- unicode`.").unwrap();
    emit_table(&mut out, "kAlphabetic", &ranges(char::is_alphabetic));
    emit_table(&mut out, "kNumeric", &ranges(char::is_numeric));
    emit_table(&mut out, "kUppercase", &ranges(char::is_uppercase));
    emit_table(&mut out, "kLowercase", &ranges(char::is_lowercase));
    // The code points whose full uppercase mapping is ASCII: all `is_tld` can ever match.
    let to_ascii: Vec<(u32, String)> = (0x80..=0x10FFFFu32)
        .filter_map(char::from_u32)
        .filter_map(|c| {
            let up: String = c.to_uppercase().collect();
            up.is_ascii().then_some((c as u32, up))
        })
        .collect();
    writeln!(out, "static const UpperToAscii kUpperToAscii[] = {{").unwrap();
    for (cp, up) in to_ascii {
        writeln!(out, "    {{0x{cp:X}, \"{up}\"}},").unwrap();
    }
    writeln!(out, "}};").unwrap();
    // Full uppercase mapping of every code point that has one (prepare_text_prompt capitalizes
    // the first character with `char::to_uppercase`), sorted by code point.
    writeln!(out, "static const UpperMapping kToUpper[] = {{").unwrap();
    for cp in 0..=0x10FFFFu32 {
        let Some(c) = char::from_u32(cp) else { continue };
        let up: Vec<char> = c.to_uppercase().collect();
        if up.len() == 1 && up[0] == c {
            continue;
        }
        let mut ups: Vec<String> = up.iter().map(|u| format!("0x{:X}", *u as u32)).collect();
        ups.resize(3, "0".into());
        writeln!(out, "    {{0x{cp:X}, {{{}}}}},", ups.join(", ")).unwrap();
    }
    writeln!(out, "}};").unwrap();
}

fn parse_lang(s: &str) -> Lang {
    s.parse().unwrap_or_else(|e| panic!("bad lang {s:?}: {e}"))
}

fn parse_rules(s: &str) -> Rules {
    s.parse().unwrap_or_else(|e| panic!("bad rules {s:?}: {e}"))
}

/// splitmix64: tiny, and trivially reproducible should the corpus ever need regenerating
/// elsewhere.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E3779B97F4A7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58476D1CE4E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D049BB133111EB);
        z ^ (z >> 31)
    }
    fn below(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }
    fn pick<'a>(&mut self, items: &[&'a str]) -> &'a str {
        items[self.below(items.len())]
    }
}

