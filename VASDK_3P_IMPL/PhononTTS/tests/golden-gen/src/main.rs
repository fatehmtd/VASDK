const SEPARATORS: &[&str] = &[" ", " ", " ", " ", " ", "", "", "  ", "\u{a0}", "\u{202f}", "\t", "\n"];
const ENDINGS: &[&str] = &["", "", "", ".", ",", "!", "?", "...", ".,", "!?", ":", ";", "\"", "'", ".'", ")"];

fn fuzz_case(rng: &mut Rng) -> String {
    let n = 1 + rng.below(8);
    let mut s = String::new();
    for i in 0..n {
        if i > 0 {
            s.push_str(rng.pick(SEPARATORS));
        }
        s.push_str(rng.pick(TOKENS));
        if rng.below(4) == 0 {
            s.push_str(rng.pick(ENDINGS));
        }
    }
    s
}

fn golden(corpus: &str, per_set: usize, seed: u64) {
    let mut out = std::io::stdout().lock();
    let mut emit = |kind: &str, lang: &str, rules: &str, text: &str| {
        let (l, r) = (parse_lang(lang), parse_rules(rules));
        let expected = match kind {
            "text" => Value::from(normalize_text(text, l, r)),
            "word" => rewrite_word(text, l, r).map_or(Value::Null, Value::from),
            // The prompt the model is given: [prepared text, frames after EOS].
            "prompt" => {
                let (prepared, frames) = ptts::tts_model::prepare_text_prompt(text);
                json!([prepared, frames])
            }
            other => panic!("unknown kind {other:?}"),
        };
        let line = json!({"kind": kind, "lang": lang, "rules": rules, "text": text, "expected": expected});
        writeln!(out, "{line}").unwrap();
    };
    let file = std::fs::File::open(corpus).unwrap_or_else(|e| panic!("{corpus}: {e}"));
    for line in std::io::BufReader::new(file).lines() {
        let line = line.unwrap();
        if line.trim().is_empty() {
            continue;
        }
        let v: Value = serde_json::from_str(&line).unwrap_or_else(|e| panic!("{line}: {e}"));
        let field = |k: &str| v[k].as_str().unwrap_or_else(|| panic!("{line}: no {k}")).to_string();
        emit(&field("kind"), &field("lang"), &field("rules"), &field("text"));
    }
    let mut rng = Rng(seed);
    for lang in ["en", "fr", "de", "es", "pt"] {
        for rules in ["default", "all", "none"] {
            for _ in 0..per_set {
                emit("text", lang, rules, &fuzz_case(&mut rng));
            }
        }
    }
    for _ in 0..per_set {
        emit("prompt", "en", "none", &fuzz_case(&mut rng));
    }
}

