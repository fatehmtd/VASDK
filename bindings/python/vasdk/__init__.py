"""VASDK agents from Python, over the C API (VASDK/c/vasdk.h) with ctypes: no compiler needed.
Data crosses as VASDK's protos, the same messages C++ uses (vasdk.engine.Event, vasdk.flow.ConversationReply, ...).

    import vasdk

    registry = vasdk.Registry()

    @registry.tool("save_booking")
    def save_booking(args):
        return {"reference": args["reference"], "status": "confirmed"}

    agent = vasdk.Agent.load("agents/garage-menu/agent.txtpb", registry)
    conversation = agent.conversation()
    conversation.start().text                    # "Hi, this is Acme Garage. ..."
    conversation.say("book a tire repair").page  # "booking"
    vasdk.run_test_file(agent, "tests/book_service.txtpb")   # (True, "")

A spoken conversation, with the speech providers an engine config names (Session):

    session = vasdk.Session("engine.txtpb", vasdk.Providers(), agent)

    @session.on_event
    def on_event(event):                         # a vasdk.Event
        if event.WhichOneof("kind") == "agent_reply" and event.agent_reply.is_final:
            print(event.agent_reply.text)

    session.on_audio(play)                       # the assistant's speech: 16-bit mono PCM bytes
    session.start()
    session.push_audio(pcm)                      # the user's audio, as it comes

The library is found from VASDK_LIBRARY (a path to libVASDK.dylib, .so or VASDK.dll), else in
this package (a wheel bundles it: see bindings/python/README.md) or in ./build/VASDK. It must be a
shared build of VASDK. The speech providers (Providers) are a library of their own,
vasdk_providers, found from VASDK_PROVIDERS_LIBRARY, else beside VASDK or in the build tree. The
messages (vasdk.engine.events_pb2, vasdk.flow.conversation_pb2, ...) are generated by the build
into build/bindings/python/vasdk (VASDK_PYTHON_PROTOS points elsewhere); they need the protobuf
package (pip install protobuf).

Tools and entity extractors take and give dicts: their data is JSON, which an LLM writes.
"""

