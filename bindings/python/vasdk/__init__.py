def set_log_level(level):
    """How much VASDK logs to the console: "trace", "debug", "info" (the default), "warn", "error" or
    "off". The speech providers' library too, now or when Providers() loads it."""
    global _log_level
    if not _set_log_level(_encode(level)):
        raise VasdkError(f"unknown log level {level!r}")
    _log_level = level
    if _providers_lib is not None and hasattr(_providers_lib, "vasdk_providers_set_log_level"):
        _providers_lib.vasdk_providers_set_log_level(_encode(level))


def words(text):
    """The words of a text as agents read them: lower case; letters, digits and apostrophes."""
    return re.findall(r"[a-z0-9'\u0080-￿]+", text.lower())


class Turn:
    """The turn a step or envelope runs in; only valid inside the callback."""

    def __init__(self, handle):
        self._handle = handle

    @property
    def text(self):
        return _turn_text(self._handle).decode("utf-8")

    def lookup(self, reference):
        """The value a reference holds now ("$session.tier", "$form.day"); None when unknown."""
        length = ctypes.c_size_t()
        return _python_value(_take_bytes(_turn_lookup_message(self._handle, _encode(reference), _BINARY, ctypes.byref(length)),
                                         length))

    def say(self, text):
        _turn_say(self._handle, _encode(text))

    def goto(self, target):
        _turn_goto(self._handle, _encode(target))

    def apply(self, outcome):
        """A vasdk.StepOutcome, or the same as a dict: {"set": {"$session.x": 1}, "unset": [...], "say": [...], "goto": "page"}."""
        if not isinstance(outcome, StepOutcome):
            outcome = json_format.ParseDict(outcome, StepOutcome())
        data = outcome.SerializeToString()
        error = ctypes.c_void_p()
        if not _turn_apply(self._handle, data, len(data), _BINARY, ctypes.byref(error)):
            raise VasdkError(_take(error.value))


class Registry:
    """Steps, tools, envelopes, page types and entity extractors written in Python, for the agents loaded with it."""

    def __init__(self):
        self._handle = _registry_create()
        self._callbacks = []   # kept alive as long as the registry

    def __del__(self):
        if getattr(self, "_handle", None):
            _registry_free(self._handle)
            self._handle = None

    def step(self, params_type, message=None):
        """A step for custom { [type.googleapis.com/<params_type>] {...} }: fn(params, turn: Turn).
        params is the message itself when Python knows its class (message=, or its _pb2 module is
        imported); else a dict (a type only the agent's .proto files declare)."""
        message = message or _message_class(params_type)

        def register(function):
            def run(params):
                def call(turn):
                    try:
                        function(params(), Turn(turn))
                    except Exception as error:   # a step that fails says nothing, as in C++
                        print(f"vasdk: step {params_type} failed: {error!r}", file=sys.stderr)
                return call

            if message:
                def callback(data, length, turn, _user):
                    run(lambda: message.FromString(_bytes_at(data, length)))(turn)
                _add_step_message(self._handle, _encode(params_type), _BINARY, self._keep(_STEP_MESSAGE(callback)), None)
            else:
                def callback(params_json, turn, _user):
                    run(lambda: json.loads(params_json.decode("utf-8")))(turn)
                _add_step(self._handle, _encode(params_type), self._keep(_STEP(callback)), None)
            return function
        return register

    def tool(self, name, description=""):
        """A tool for call_tool steps: fn(args: dict) -> result; raising fails the call (tool-error)."""
        def register(function):
            _add_tool(self._handle, _encode(name), _encode(description), self._keep(_tool_callback(function)), None)
            return function
        return register

    def envelope(self, name, before=None, after=None):
        """An envelope: before(turn) -> True when it answered the turn; after(turn) on the reply."""
        def call_before(turn, _user):
            try:
                return 1 if before(Turn(turn)) else 0
            except Exception as error:
                print(f"vasdk: envelope {name} failed: {error!r}", file=sys.stderr)
                return 0

        def call_after(turn, _user):
            try:
                after(Turn(turn))
            except Exception as error:
                print(f"vasdk: envelope {name} failed: {error!r}", file=sys.stderr)

        before_callback = self._keep(_BEFORE(call_before)) if before else _BEFORE()
        after_callback = self._keep(_AFTER(call_after)) if after else _AFTER()
        _add_envelope(self._handle, _encode(name), before_callback, after_callback, None)

    def page_type(self, name, params_type=None, on_enter=None, on_turn=None, message=None):
        """A page type for pages with type: "<name>": on_enter(params, turn) when the page is
        entered; on_turn(params, turn) -> True when it answered the turn (else the page's routes
        get it). params_type: the full name of its params message, None for no params (params is
        then None). params is the message itself when Python knows its class (message=, or its
        _pb2 module is imported); else a dict."""
        message = message or (_message_class(params_type) if params_type else None)

        def guarded(function, failed):
            try:
                return function()
            except Exception as error:
                print(f"vasdk: page type {name} failed: {error!r}", file=sys.stderr)
                return failed

        if message or not params_type:
            def params_of(data, length):
                return message.FromString(_bytes_at(data, length)) if message else None

            def call_enter(data, length, turn, _user):
                guarded(lambda: on_enter(params_of(data, length), Turn(turn)), None)

            def call_turn(data, length, turn, _user):
                return 1 if guarded(lambda: on_turn(params_of(data, length), Turn(turn)), False) else 0

            enter_callback = self._keep(_PAGE_ENTER_MESSAGE(call_enter)) if on_enter else _PAGE_ENTER_MESSAGE()
            turn_callback = self._keep(_PAGE_TURN_MESSAGE(call_turn)) if on_turn else _PAGE_TURN_MESSAGE()
            ok = _add_page_type_message(self._handle, _encode(name), _encode(params_type), _BINARY, enter_callback,
                                        turn_callback, None)
        else:
            def call_enter(params_json, turn, _user):
                guarded(lambda: on_enter(json.loads(params_json.decode("utf-8")), Turn(turn)), None)

            def call_turn(params_json, turn, _user):
                return 1 if guarded(lambda: on_turn(json.loads(params_json.decode("utf-8")), Turn(turn)), False) else 0

            enter_callback = self._keep(_PAGE_ENTER(call_enter)) if on_enter else _PAGE_ENTER()
            turn_callback = self._keep(_PAGE_TURN(call_turn)) if on_turn else _PAGE_TURN()
            ok = _add_page_type(self._handle, _encode(name), _encode(params_type), enter_callback, turn_callback, None)
        if not ok:
            raise VasdkError(f"page type {name!r} didn't register")

    def entity_extractor(self, name):
        """Finds the values of code { extractor: "<name>" } entities: fn(words: list, text: str) ->
        [{"start": 2, "length": 1, "value": ..., "spoken": "Mom", "attributes": {...}}] (start and
        length index the words). Called each time the entity is looked for: keep it quick."""
        def register(function):
            def callback(request_json, result, _user):
                try:
                    request = json.loads(request_json.decode("utf-8"))
                    _result_set(result, _encode(json.dumps(list(function(request["words"], request["text"])))))
                except Exception as error:
                    _result_fail(result, _encode(str(error) or type(error).__name__))
            if not _add_entity_extractor(self._handle, _encode(name), self._keep(_EXTRACTOR(callback)), None):
                raise VasdkError(f"entity extractor {name!r} didn't register")
            return function
        return register

    def _keep(self, callback):
        self._callbacks.append(callback)
        return callback


class Agent:
    """An agent, checked and compiled: Agent.load(path), or Agent.parse(a vasdk.flow.Agent message,
    or its text, JSON or bytes)."""

    def __init__(self, handle, registry):
        self._handle = handle
        self._registry = registry   # its callbacks must outlive the agent

    @classmethod
    def load(cls, path, registry=None):
        error = ctypes.c_void_p()
        handle = _agent_load(_encode(str(path)), registry._handle if registry else None, ctypes.byref(error))
        if not handle:
            raise VasdkError(_take(error.value))
        return cls(handle, registry)

    @classmethod
    def parse(cls, agent, registry=None, format="text"):
        """agent: a vasdk.flow.agent_pb2.Agent, or the agent in `format` ("text", "json", "binary")."""
        if hasattr(agent, "SerializeToString"):
            data, format = agent.SerializeToString(), "binary"
        else:
            data = agent.encode("utf-8") if isinstance(agent, str) else bytes(agent)
        error = ctypes.c_void_p()
        handle = _agent_parse(data, len(data), _FORMATS[format], registry._handle if registry else None, ctypes.byref(error))
        if not handle:
            raise VasdkError(_take(error.value))
        return cls(handle, registry)

    def conversation(self):
        return Conversation(self)

    def __del__(self):
        if getattr(self, "_handle", None):
            _agent_free(self._handle)
            self._handle = None


class Conversation:
    """One conversation's place in an agent, by text. Each turn returns a vasdk.ConversationReply:
    text, segments, choices, matched, intent, event, expects_reply, ends_session, to_llm,
    llm_profile, flow, page, tool_calls, triggers. With to_llm, a route handed the turn to an LLM:
    answer it with yours (llm_profile says which); text is the answer without one."""

    def __init__(self, agent):
        self._agent = agent
        self._handle = _conversation_create(agent._handle)

    def __del__(self):
        if getattr(self, "_handle", None):
            _conversation_free(self._handle)
            self._handle = None

    def send(self, input):
        """A vasdk.ConversationInput (start, text, no_input, select_choice, fire_trigger): its reply."""
        data = input.SerializeToString()
        length, error = ctypes.c_size_t(), ctypes.c_void_p()
        reply = _conversation_send(self._handle, data, len(data), _BINARY, ctypes.byref(length), ctypes.byref(error))
        if not reply:
            raise VasdkError(_take(error.value) or "failed")
        return ConversationReply.FromString(_take_bytes(reply, length))

    def start(self):
        return self.send(ConversationInput(start=True))

    def say(self, text):
        return self.send(ConversationInput(text=text))

    def no_input(self):
        return self.send(ConversationInput(no_input=True))

    def select_choice(self, index):
        return self.send(ConversationInput(select_choice=index))

    def fire_trigger(self, name, payload=None):
        """payload: a dict (or a Struct), $trigger.payload."""
        input = ConversationInput()
        input.fire_trigger.name = name
        input.fire_trigger.payload.CopyFrom(_struct_message(payload))
        return self.send(input)

    def set_param(self, name, value):
        data = _value_message(value).SerializeToString()
        error = ctypes.c_void_p()
        if not _conversation_set_param(self._handle, _encode(name), data, len(data), _BINARY, ctypes.byref(error)):
            raise VasdkError(_take(error.value))

    def lookup(self, reference):
        """The value a reference holds now ("$session.reference"), as a Python value; None when unknown."""
        length = ctypes.c_size_t()
        return _python_value(_take_bytes(_conversation_lookup(self._handle, _encode(reference), _BINARY, ctypes.byref(length)),
                                         length))


def run_test_file(agent, path):
    """Plays a FlowTestCase file: (passed, report), the report a line per difference."""
    report = ctypes.c_void_p()
    passed = bool(_run_test_file(agent._handle, _encode(str(path)), ctypes.byref(report)))
    return passed, _take(report.value) or ""


class Providers:
    """The speech providers an engine config can name (VAD, STT, TTS, turn detection): every one
    built into the vasdk_providers library."""

    def __init__(self):
        global _providers_lib
        if _providers_lib is None:
            library = _load(_find_providers_library(_library_path))
            library.vasdk_providers_add_all.restype = None
            library.vasdk_providers_add_all.argtypes = [_p]
            if hasattr(library, "vasdk_providers_set_log_level"):
                library.vasdk_providers_set_log_level.restype = _i
                library.vasdk_providers_set_log_level.argtypes = [_s]
                if _log_level:
                    library.vasdk_providers_set_log_level(_encode(_log_level))
            _providers_lib = library
        self._handle = _providers_create()
        _providers_lib.vasdk_providers_add_all(self._handle)

    def __del__(self):
        if getattr(self, "_handle", None):
            _providers_free(self._handle)
            self._handle = None


class Session:
    """A spoken conversation: the providers and the LLM an engine config names, and an agent (or
    None for the LLM alone). The app brings the audio: push_audio() the user's 16-bit mono PCM,
    and get the assistant's speech through on_audio(). Or type: inject_text().

        session = vasdk.Session("engine.txtpb", vasdk.Providers(), agent, models_dir="models")

        @session.tool("set_timer", "Starts a kitchen timer", [{"name": "minutes", "type": "number"}])
        def set_timer(args):
            return {"started": args["minutes"]}

        session.on_event(print)          # each vasdk.Event
        session.start()
        session.inject_text("set a timer for five minutes")

    on_event, on_audio and tool() come before start(). Callbacks run on VASDK's threads: keep them
    quick, and hand longer work to threads of your own."""

    def __init__(self, config, providers, agent=None, id=None, models_dir=None, system_prompt=None, format_instruction=None,
                 options=None):
        """system_prompt: the LLM's instructions ({context} in them is set_context's state);
        format_instruction: how its replies must be formatted, appended to every request.
        options: a vasdk.SessionOptions instead of the keyword arguments."""
        if options is None:
            options = SessionOptions(id=id or "", models_dir=str(models_dir) if models_dir else "",
                                     system_prompt=system_prompt or "", format_instruction=format_instruction or "")
        data = options.SerializeToString()
        error = ctypes.c_void_p()
        handle = _session_create(_encode(str(config)), providers._handle, agent._handle if agent else None, data, len(data),
                                 _BINARY, ctypes.byref(error))
        if not handle:
            raise VasdkError(_take(error.value))
        self._handle = handle
        self._providers, self._agent = providers, agent   # must outlive the session
        self._callbacks = []
        self._lock = threading.Lock()

    def close(self):
        """Stops it and frees it."""
        if getattr(self, "_handle", None):
            _session_free(self._handle)
            self._handle = None

    def __del__(self):
        self.close()

    def __enter__(self):
        return self

    def __exit__(self, *_):
        self.close()

    @property
    def input_rate(self):
        return _session_input_rate(self._handle)

    @property
    def output_rate(self):
        return _session_output_rate(self._handle)

    def on_event(self, function):
        """fn(event: vasdk.Event) for each event: event.WhichOneof("kind") is "transcript",
        "agent_reply", "tool_call", "page_changed", ... (vasdk/engine/events.proto). Usable as a decorator."""
        def callback(data, length, _user):
            try:
                function(Event.FromString(_bytes_at(data, length)))
            except Exception as error:
                print(f"vasdk: on_event failed: {error!r}", file=sys.stderr)
        _session_on_event(self._handle, self._keep(_MESSAGE(callback)), _BINARY, None)
        return function

    def on_audio(self, function):
        """fn(pcm: bytes): the assistant's speech, 16-bit mono at output_rate. Usable as a decorator."""
        def callback(pcm, samples, _user):
            try:
                function(ctypes.string_at(pcm, samples * 2))
            except Exception as error:
                print(f"vasdk: on_audio failed: {error!r}", file=sys.stderr)
        _session_on_audio(self._handle, self._keep(_AUDIO(callback)), None)
        return function

    def tool(self, name, description="", parameters=None):
        """A tool the session's LLM may call: fn(args: dict) -> result, as a decorator. parameters:
        vasdk.ToolParameter messages, or the same as dicts: [{"name": "minutes", "description":
        "...", "type": "number", "required": True}]. Raising fails the call, and the LLM is told
        why. (An agent's call_tool tools go in its Registry.)"""
        declaration = ToolDeclaration(name=name, description=description)
        for parameter in parameters or []:
            declaration.parameters.append(parameter if isinstance(parameter, ToolParameter)
                                          else json_format.ParseDict(parameter, ToolParameter()))

        def register(function):
            data = declaration.SerializeToString()
            error = ctypes.c_void_p()
            _check(_session_add_tool(self._handle, data, len(data), _BINARY, self._keep(_tool_callback(function)), None,
                                     ctypes.byref(error)), error)
            return function
        return register

    def start(self, resume=None):
        """Starts listening and speaking. resume: a snapshot() from an earlier session to pick up (a
        vasdk.ConversationSnapshot, its serialized bytes, or its JSON)."""
        if resume:
            if isinstance(resume, str):
                resume = json_format.Parse(resume, ConversationSnapshot(), ignore_unknown_fields=True)
            data = resume if isinstance(resume, bytes) else resume.SerializeToString()
            error = ctypes.c_char_p()
            _check(_session_resume(self._handle, data, len(data), _BINARY, ctypes.byref(error)), error)
        error = ctypes.c_void_p()
        _check(_session_start(self._handle, ctypes.byref(error)), error)

    def stop(self):
        _session_stop(self._handle)

    def push_audio(self, pcm):
        """The user's audio: 16-bit mono PCM at input_rate, as bytes (or anything with the buffer protocol)."""
        data = bytes(pcm)
        if data:
            _session_push_audio(self._handle, ctypes.cast(ctypes.c_char_p(data), _p), len(data) // 2)

    def send(self, command):
        """Does what a vasdk.Command asks: inject_text, select_choice, fire_trigger, say, interrupt,
        set_session_param. The methods below are shortcuts."""
        data = command.SerializeToString()
        error = ctypes.c_void_p()
        _check(_session_send(self._handle, data, len(data), _BINARY, ctypes.byref(error)), error)

    def inject_text(self, text):
        """A user turn by text, as if spoken."""
        self.send(Command(inject_text=text))

    def say(self, text):
        """Words the assistant says."""
        self.send(Command(say=text))

    def select_choice(self, index):
        """The user picked the last reply's choice at `index` (from 0)."""
        self.send(Command(select_choice=index))

    def interrupt(self):
        """Stops the reply playing, like the user talking over it."""
        self.send(Command(interrupt=True))

    def set_param(self, name, value):
        """Sets a declared $session.<name> of the agent."""
        command = Command()
        command.set_session_param.name = name
        command.set_session_param.value.CopyFrom(_value_message(value))
        self.send(command)

    def fire_trigger(self, name, payload=None):
        """Fires the agent's app_event triggers named `name`; payload (a dict or a Struct) is $trigger.payload."""
        command = Command()
        command.fire_trigger.name = name
        command.fire_trigger.payload.CopyFrom(_struct_message(payload))
        self.send(command)

    def set_context(self, context):
        """The app's state, a dict (or a Struct): what the agent's $context.* reads (and its
        context_change triggers watch), and {context} in the LLM's instructions. Each top-level key is replaced."""
        data = _struct_message(context).SerializeToString()
        error = ctypes.c_void_p()
        _check(_session_set_context(self._handle, data, len(data), _BINARY, ctypes.byref(error)), error)

    def set_network_available(self, available):
        _session_set_network(self._handle, 1 if available else 0)

    def snapshot(self):
        """Where the agent's conversation is, to start(resume=...) a later session there: a
        vasdk.ConversationSnapshot (its flow empty when there's nothing to resume). Store it with
        SerializeToString(), or json_format.MessageToJson()."""
        length = ctypes.c_size_t()
        snapshot = ConversationSnapshot()
        snapshot.ParseFromString(_take_bytes(_session_snapshot(self._handle, _BINARY, ctypes.byref(length)), length))
        return snapshot

    def _keep(self, callback):
        with self._lock:
            self._callbacks.append(callback)
        return callback
