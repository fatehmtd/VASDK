def _check(ok, error):
    if not ok:
        raise VasdkError(_take(error.value) or "failed")


def _take(pointer):
    """The text VASDK returned, freed."""
    if not pointer:
        return None
    try:
        return ctypes.string_at(pointer).decode("utf-8")
    finally:
        _free(pointer)


def _take_bytes(pointer, length):
    """The message VASDK returned, `length` bytes, freed."""
    if not pointer:
        return b""
    try:
        return ctypes.string_at(pointer, length.value)
    finally:
        _free(pointer)


def _bytes_at(data, length):
    """A message VASDK gives a callback: valid only during it."""
    return ctypes.string_at(data, length) if data and length else b""


def _encode(text):
    return text.encode("utf-8") if text is not None else None


def _whole(value):
    """A google.protobuf.Value's numbers are doubles: 3.0 back as 3, as JSON reads it."""
    if isinstance(value, float) and value.is_integer():
        return int(value)
    if isinstance(value, list):
        return [_whole(item) for item in value]
    if isinstance(value, dict):
        return {key: _whole(item) for key, item in value.items()}
    return value


def _value_message(value):
    """A Python value (None, bool, number, str, list, dict) as a google.protobuf.Value."""
    if isinstance(value, struct_pb2.Value):
        return value
    message = struct_pb2.Value()
    json_format.ParseDict(value, message)
    return message


def _python_value(data):
    """A serialized google.protobuf.Value as a Python value."""
    message = struct_pb2.Value()
    message.ParseFromString(data)
    return _whole(json_format.MessageToDict(message))


def _struct_message(values):
    """A dict (or a Struct) as a google.protobuf.Struct."""
    if isinstance(values, struct_pb2.Struct):
        return values
    message = struct_pb2.Struct()
    if values:
        message.update(values)
    return message


def _message_class(full_name):
    """The Python class of a message type, when its module is imported (VASDK's, google's, the app's); else None."""
    try:
        return message_factory.GetMessageClass(descriptor_pool.Default().FindMessageTypeByName(full_name))
    except KeyError:
        return None


def _params_from_json(params_type, params_json):
    """A step's or page type's params, given as JSON: its message when Python knows the class by
    now (an agent's proto_imports add theirs when it loads), else a dict."""
    text = params_json.decode("utf-8")
    cls = _message_class(params_type) if params_type else None
    return json_format.Parse(text, cls(), ignore_unknown_fields=True) if cls else json.loads(text)


