class Sink:
    """How a provider written in Python gives back what it finds or makes, from any thread, for as
    long as the provider lives: transcripts (STT), speech (TTS), errors."""

    def __init__(self, handle):
        self._handle = handle

    def text(self, text, final=True):
        """A transcript: final, or a partial (final=False)."""
        _sink_text(self._handle, _encode(text), 1 if final else 0)

    def audio(self, pcm):
        """Speech, 16-bit mono PCM bytes at the session's output rate, in order."""
        data = bytes(pcm)
        if data:
            _sink_audio(self._handle, ctypes.cast(ctypes.c_char_p(data), _p), len(data) // 2)

    def done(self):
        """The text given to synthesize() is all said."""
        _sink_done(self._handle)

    def error(self, message):
        _sink_error(self._handle, _encode(message))


class Providers:
    """The providers an engine config can name by id: every one built into the vasdk_providers
    library (built_in=True), and those written in Python with the decorators below.

        providers = vasdk.Providers()

        @providers.vad("loudness")
        class Loudness:
            def __init__(self, sink, sample_rate): ...
            def detect(self, pcm): return 1.0 if max(...) > 1000 else 0.0

    The engine config then names it: providers { vad { id: "loudness" } }. Each session gets its
    own instance: cls(sink, sample_rate), sink a vasdk.Sink. Methods run on VASDK's threads; an
    exception is printed and counts as no result. What each kind implements:
      vad:              detect(pcm) -> chance of speech, 0 to 1
      stt:              write(pcm); end_of_speech(); start(), stop() optional. Results with
                        sink.text(); with streaming_transcription off (the default), write() gets the
                        whole utterance and the final must be given before end_of_speech() returns
      tts:              synthesize(text) -> True; speech with sink.audio(), then sink.done(); cancel() optional
      turn:             evaluate(pcm) -> chance, 0 to 1, that the user is done (pcm since they began speaking)
      wake_word:        process(pcm) -> (phrase, confidence) when it completes the phrase, else None
      audio_dsp:        process(pcm) -> bytes of the same length (the microphone's audio, cleaned), or None to pass it on
      speaker_embedding: embed(pcm) -> list of floats, one utterance's voice print (the same length each time)
      sentence_encoder: encode(sentence) -> list of floats, normalized; one instance for every session
      entity_model:     extract(words, labels, sensitive) -> [{"entity", "start", "length", "score"}]; one instance
      llm:              complete(messages) -> reply text, messages [{"role", "content"}]; cancel() optional
    """

    def __init__(self, built_in=True):
        global _providers_lib
        self._handle = _providers_create()
        self._callbacks = []
        self._instances = {}   # instance id -> the Python object, while C holds it
        self._next = 0
        self._lock = threading.Lock()
        if not built_in:
            return
        if _providers_lib is None:
            library = _load(_find_providers_library(_library_path))
            library.vasdk_providers_add_all.restype = None
            library.vasdk_providers_add_all.argtypes = [_p]
            if hasattr(library, "vasdk_providers_set_log_level"):
                library.vasdk_providers_set_log_level.restype = _i
                library.vasdk_providers_set_log_level.argtypes = [_s]
                if _log_level:
                    library.vasdk_providers_set_log_level(_encode(_log_level))
            _providers_lib = library
        _providers_lib.vasdk_providers_add_all(self._handle)

    def __del__(self):
        if getattr(self, "_handle", None):
            _providers_free(self._handle)
            self._handle = None

    def _keep(self, callback):
        self._callbacks.append(callback)
        return callback

    def _of(self, instance):
        with self._lock:
            return self._instances.get(instance)

    def _lifecycle(self, cls):
        def create(sink, sample_rate, _user):
            try:
                made = cls(Sink(sink), sample_rate)
            except Exception as error:
                _report(f"{cls.__name__}()", error)
                return None
            with self._lock:
                self._next += 1
                self._instances[self._next] = made
                return self._next

        def destroy(instance):
            with self._lock:
                made = self._instances.pop(instance, None)
            close = getattr(made, "close", None)
            if close:
                close()
        return self._keep(_CREATE(create)), self._keep(_DESTROY(destroy))

    def _call(self, instance, method, *arguments, default=None):
        made = self._of(instance)
        function = getattr(made, method, None) if made is not None else None
        if function is None:
            return default
        try:
            return function(*arguments)
        except Exception as error:
            _report(f"{type(made).__name__}.{method}", error)
            return default

    def _register(self, adder, name, *arguments):
        if not adder(self._handle, _encode(name), *arguments, None):
            raise VasdkError(f"provider {name!r} not added")

    def vad(self, id):
        def register(cls):
            create, destroy = self._lifecycle(cls)
            detect = self._keep(_VAD(lambda instance, pcm, samples:
                                     float(self._call(instance, "detect", _pcm_bytes(pcm, samples), default=0.0) or 0.0)))
            self._register(_add_vad, id, create, destroy, detect)
            return cls
        return register

    def stt(self, id):
        def register(cls):
            create, destroy = self._lifecycle(cls)
            event = lambda method: self._keep(_STT_EVENT(lambda instance: self._call(instance, method)))
            write = self._keep(_STT_WRITE(lambda instance, pcm, samples: self._call(instance, "write", _pcm_bytes(pcm, samples))))
            self._register(_add_stt, id, create, destroy, event("start"), write, event("end_of_speech"), event("stop"))
            return cls
        return register

    def tts(self, id):
        def register(cls):
            create, destroy = self._lifecycle(cls)
            synthesize = self._keep(_TTS_SYNTHESIZE(lambda instance, text:
                                                    1 if self._call(instance, "synthesize", text.decode("utf-8")) else 0))
            cancel = self._keep(_INSTANCE(lambda instance: self._call(instance, "cancel")))
            self._register(_add_tts, id, create, destroy, synthesize, cancel)
            return cls
        return register

    def turn(self, id):
        def register(cls):
            create, destroy = self._lifecycle(cls)
            evaluate = self._keep(_TURN(lambda instance, pcm, samples:
                                        float(self._call(instance, "evaluate", _pcm_bytes(pcm, samples), default=0.0) or 0.0)))
            self._register(_add_turn, id, create, destroy, evaluate)
            return cls
        return register

    def wake_word(self, id):
        def register(cls):
            create, destroy = self._lifecycle(cls)

            def process(instance, pcm, samples, phrase):
                found = self._call(instance, "process", _pcm_bytes(pcm, samples))
                if not found:
                    return 0.0
                _result_set(phrase, _encode(found[0]))
                return float(found[1])
            self._register(_add_wake_word, id, create, destroy, self._keep(_WAKE_WORD(process)))
            return cls
        return register

    def audio_dsp(self, id):
        def register(cls):
            create, destroy = self._lifecycle(cls)

            def process(instance, pcm, output, samples):
                changed = self._call(instance, "process", _pcm_bytes(pcm, samples))
                if changed is not None and len(changed) == samples * 2:
                    ctypes.memmove(output, bytes(changed), samples * 2)
            self._register(_add_audio_dsp, id, create, destroy, self._keep(_AUDIO_DSP(process)))
            return cls
        return register

    def speaker_embedding(self, id):
        def register(cls):
            create, destroy = self._lifecycle(cls)

            def embed(instance, pcm, samples, voice_print):
                values = self._call(instance, "embed", _pcm_bytes(pcm, samples))
                if values:
                    _result_set_floats(voice_print, (_f * len(values))(*values), len(values))
            self._register(_add_speaker_embedding, id, create, destroy, self._keep(_SPEAKER_EMBEDDING(embed)))
            return cls
        return register

    def sentence_encoder(self, id):
        def register(cls):
            create, destroy = self._lifecycle(cls)

            def encode(instance, sentence, vector):
                values = self._call(instance, "encode", sentence.decode("utf-8"))
                if values:
                    array = (_f * len(values))(*values)
                    _result_set_floats(vector, array, len(values))
            self._register(_add_sentence_encoder, id, create, destroy, self._keep(_INSTANCE_TEXT(encode)))
            return cls
        return register

    def entity_model(self, id):
        def register(cls):
            create, destroy = self._lifecycle(cls)

            def extract(instance, request_json, spans):
                request = json.loads(request_json.decode("utf-8"))
                found = self._call(instance, "extract", request["words"], request["labels"], request["sensitive"], default=[])
                _result_set(spans, _encode(json.dumps(found or [])))
            self._register(_add_entity_model, id, create, destroy, self._keep(_INSTANCE_TEXT(extract)))
            return cls
        return register

    def llm(self, id):
        def register(cls):
            create, destroy = self._lifecycle(cls)

            def complete(instance, request_json, reply):
                messages = json.loads(request_json.decode("utf-8"))["messages"]
                made = self._of(instance)
                try:
                    _result_set(reply, _encode(made.complete(messages)))
                except Exception as error:
                    _result_fail(reply, _encode(str(error) or type(error).__name__))
            cancel = self._keep(_INSTANCE(lambda instance: self._call(instance, "cancel")))
            self._register(_add_llm, id, create, destroy, self._keep(_INSTANCE_TEXT(complete)), cancel)
            return cls
        return register


class Models:
    """The model store (docs/models.md): downloads the model files local providers load, checks
    each against the SHA-256 the manifest pins, and puts them where a session looks when its
    models_dir is unset (Models.default_directory()).

        models = vasdk.Models()                          # VASDK_MODELS_DIR, else the user cache
        for model_id in models.for_config("engine.txtpb"):
            models.pull(model_id, progress=lambda model, file, done, total: print(f"{model}: {done}/{total}"))

    directory: where to keep them; manifest_path: another manifest than the built-in one; token: a
    Hugging Face token for gated models (else HF_TOKEN); offline: never download."""

    _STATUSES = {-1: "unknown", 0: "missing", 1: "partial", 2: "present"}

    def __init__(self, directory=None, manifest_path=None, token=None, offline=False, architecture=None):
        options = {"directory": str(directory) if directory else None, "manifest_path": str(manifest_path) if manifest_path else None,
                   "token": token, "offline": bool(offline) or None, "architecture": architecture}
        options = {key: value for key, value in options.items() if value is not None}
        error = ctypes.c_void_p()
        handle = _models_create(_encode(json.dumps(options)) if options else None, ctypes.byref(error))
        if not handle:
            raise VasdkError(_take(error.value))
        self._handle = handle

    def close(self):
        if getattr(self, "_handle", None):
            _models_free(self._handle)
            self._handle = None

    def __del__(self):
        self.close()

    @staticmethod
    def default_directory():
        """Where sessions look when models_dir is unset, and where a Models() downloads."""
        return _take(_models_default_directory())

    @property
    def directory(self):
        return _models_directory(self._handle).decode("utf-8")

    def list(self):
        """Every model of this machine: dicts with id, description, providers, license, license_url,
        revision, gated, requires_acceptance, size, status ("present", "partial", "missing") and files."""
        return json.loads(_take(_models_list(self._handle)))

    def for_config(self, config_path):
        """The ids of the models an engine config's providers load."""
        error = ctypes.c_void_p()
        ids = _models_for_config(self._handle, _encode(str(config_path)), ctypes.byref(error))
        if not ids:
            raise VasdkError(_take(error.value))
        return json.loads(_take(ids))

    def status(self, model_id):
        """"present", "partial", "missing", or "unknown" (not in the manifest)."""
        return self._STATUSES[_models_status(self._handle, _encode(model_id))]

    def pull(self, model_id, accept_license=False, progress=None):
        """Downloads what is missing of the model, resuming a stopped download. accept_license: you read
        the license of a model marked requires_acceptance. progress(model, file, done, total) is called as
        bytes arrive; returning False stops the pull. Blocks until done."""
        def call(model, file, done, total, _user):
            try:
                return 0 if progress(model.decode(), file.decode(), done, total) is False else 1
            except Exception:   # noqa: BLE001 - an exception can't cross into C: stop the pull
                return 0
        callback = _MODEL_PROGRESS(call) if progress else _MODEL_PROGRESS()
        error = ctypes.c_void_p()
        _check(_models_pull(self._handle, _encode(model_id), 1 if accept_license else 0, callback, None, ctypes.byref(error)), error)

    def verify(self, model_id):
        """Hashes the model's files; raises VasdkError when one is missing or doesn't match."""
        error = ctypes.c_void_p()
        _check(_models_verify(self._handle, _encode(model_id), ctypes.byref(error)), error)

    def remove(self, model_id):
        error = ctypes.c_void_p()
        _check(_models_remove(self._handle, _encode(model_id), ctypes.byref(error)), error)


class Runtime:
    """What many sessions share: the engine config and its providers, loaded once per session
    running at the same time (a call center's lines), not once per conversation.

        runtime = vasdk.Runtime("engine.txtpb", vasdk.Providers(), max_sessions=4)
        call = runtime.session(agent, id="call-1")

    Free the sessions (close()) before the runtime."""

    def __init__(self, config, providers, models_dir=None, max_sessions=0):
        """config: an engine config file's path, or a vasdk.EngineConfig built in code."""
        error = ctypes.c_void_p()
        models = _encode(str(models_dir)) if models_dir else None
        if isinstance(config, EngineConfig):
            built = config.SerializeToString()
            handle = _runtime_create_config(built, len(built), _BINARY, providers._handle, models, int(max_sessions),
                                            ctypes.byref(error))
        else:
            handle = _runtime_create(_encode(str(config)), providers._handle, models, int(max_sessions), ctypes.byref(error))
        if not handle:
            raise VasdkError(_take(error.value))
        self._handle, self._providers = handle, providers

    def close(self):
        if getattr(self, "_handle", None):
            _runtime_free(self._handle)
            self._handle = None

    def __del__(self):
        self.close()

    def session(self, agent=None, id=None, system_prompt=None, format_instruction=None, options=None):
        """A session over the runtime's providers, as Session() takes them."""
        if options is None:
            options = SessionOptions(id=id or "", system_prompt=system_prompt or "", format_instruction=format_instruction or "")
        data = options.SerializeToString()
        error = ctypes.c_void_p()
        handle = _runtime_session_create(self._handle, agent._handle if agent else None, data, len(data), _BINARY,
                                         ctypes.byref(error))
        if not handle:
            raise VasdkError(_take(error.value))
        session = Session.__new__(Session)
        session._adopt(handle, self, agent)
        return session

    def active_sessions(self):
        return _runtime_active_sessions(self._handle)

    def idle_provider_sets(self):
        """Provider sets loaded and waiting for a session."""
        return _runtime_idle_provider_sets(self._handle)


class Session:
    """A spoken conversation: the providers and the LLM an engine config names, and an agent (or
    None for the LLM alone). The app brings the audio: push_audio() the user's 16-bit mono PCM,
    and get the assistant's speech through on_audio(). Or type: inject_text().
    A config whose providers name a webrtc peer (providers { webrtc { id: "libdatachannel" } })
    talks to a browser instead, and push_audio() and on_audio() go unused.

        session = vasdk.Session("engine.txtpb", vasdk.Providers(), agent, models_dir="models")

        @session.tool("set_timer", "Starts a kitchen timer", [{"name": "minutes", "type": "number"}])
        def set_timer(args):
            return {"started": args["minutes"]}

        session.on_event(print)          # each vasdk.Event
        session.start()
        session.inject_text("set a timer for five minutes")

    on_event, on_audio and tool() come before start(). Callbacks run on VASDK's threads: keep them
    quick, and hand longer work to threads of your own."""

    def __init__(self, config, providers, agent=None, id=None, models_dir=None, system_prompt=None, format_instruction=None,
                 options=None):
        """config: an engine config file's path, or a vasdk.EngineConfig built in code, its
        providers' options their own messages (vasdk.providers.options_pb2.PhononOptions, ...);
        system_prompt: the LLM's instructions ({context} in them is set_context's state);
        format_instruction: how its replies must be formatted, appended to every request.
        options: a vasdk.SessionOptions instead of the keyword arguments."""
        if options is None:
            options = SessionOptions(id=id or "", models_dir=str(models_dir) if models_dir else "",
                                     system_prompt=system_prompt or "", format_instruction=format_instruction or "")
        data = options.SerializeToString()
        error = ctypes.c_void_p()
        agent_handle = agent._handle if agent else None
        if isinstance(config, EngineConfig):
            built = config.SerializeToString()
            handle = _session_create_config(built, len(built), _BINARY, providers._handle, agent_handle, data, len(data),
                                            _BINARY, ctypes.byref(error))
        else:
            handle = _session_create(_encode(str(config)), providers._handle, agent_handle, data, len(data), _BINARY,
                                     ctypes.byref(error))
        if not handle:
            raise VasdkError(_take(error.value))
        self._adopt(handle, providers, agent)

    def _adopt(self, handle, owner, agent):
        self._handle = handle
        self._providers, self._agent = owner, agent   # must outlive the session
        self._callbacks = []
        self._lock = threading.Lock()

    def close(self):
        """Stops it and frees it."""
        if getattr(self, "_handle", None):
            _session_free(self._handle)
            self._handle = None

    def __del__(self):
        self.close()

    def __enter__(self):
        return self

    def __exit__(self, *_):
        self.close()

    @property
    def input_rate(self):
        return _session_input_rate(self._handle)

    @property
    def output_rate(self):
        return _session_output_rate(self._handle)

    def on_event(self, function):
        """fn(event: vasdk.Event) for each event: event.WhichOneof("kind") is "transcript",
        "agent_reply", "tool_call", "page_changed", ... (vasdk/engine/events.proto). Usable as a decorator."""
        def callback(data, length, _user):
            try:
                function(Event.FromString(_bytes_at(data, length)))
            except Exception as error:
                print(f"vasdk: on_event failed: {error!r}", file=sys.stderr)
        _session_on_event(self._handle, self._keep(_MESSAGE(callback)), _BINARY, None)
        return function

    def on_audio(self, function):
        """fn(pcm: bytes): the assistant's speech, 16-bit mono at output_rate. Usable as a decorator."""
        def callback(pcm, samples, _user):
            try:
                function(ctypes.string_at(pcm, samples * 2))
            except Exception as error:
                print(f"vasdk: on_audio failed: {error!r}", file=sys.stderr)
        _session_on_audio(self._handle, self._keep(_AUDIO(callback)), None)
        return function

    def tool(self, name, description="", parameters=None):
        """A tool the session's LLM may call: fn(args: dict) -> result, as a decorator. parameters:
        vasdk.ToolParameter messages, or the same as dicts: [{"name": "minutes", "description":
        "...", "type": "number", "required": True}]. Raising fails the call, and the LLM is told
        why. (An agent's call_tool tools go in its Registry.)"""
        declaration = ToolDeclaration(name=name, description=description)
        for parameter in parameters or []:
            declaration.parameters.append(parameter if isinstance(parameter, ToolParameter)
                                          else json_format.ParseDict(parameter, ToolParameter()))

        def register(function):
            data = declaration.SerializeToString()
            error = ctypes.c_void_p()
            _check(_session_add_tool(self._handle, data, len(data), _BINARY, self._keep(_tool_callback(function)), None,
                                     ctypes.byref(error)), error)
            return function
        return register

    def start(self, resume=None):
        """Starts listening and speaking. resume: a snapshot() from an earlier session to pick up (a
        vasdk.ConversationSnapshot, its serialized bytes, or its JSON)."""
        if resume:
            if isinstance(resume, str):
                resume = json_format.Parse(resume, ConversationSnapshot(), ignore_unknown_fields=True)
            data = resume if isinstance(resume, bytes) else resume.SerializeToString()
            error = ctypes.c_char_p()
            _check(_session_resume(self._handle, data, len(data), _BINARY, ctypes.byref(error)), error)
        error = ctypes.c_void_p()
        _check(_session_start(self._handle, ctypes.byref(error)), error)

    def stop(self):
        _session_stop(self._handle)

    def push_audio(self, pcm):
        """The user's audio: 16-bit mono PCM at input_rate, as bytes (or anything with the buffer protocol)."""
        data = bytes(pcm)
        if data:
            _session_push_audio(self._handle, ctypes.cast(ctypes.c_char_p(data), _p), len(data) // 2)

    def send(self, command):
        """Does what a vasdk.Command asks: inject_text, select_choice, fire_trigger, say, interrupt,
        set_session_param, reset_conversation, push_to_talk, follow_up_listen_ms, set_entity_values,
        set_backchannel. The methods below are shortcuts."""
        data = command.SerializeToString()
        error = ctypes.c_void_p()
        _check(_session_send(self._handle, data, len(data), _BINARY, ctypes.byref(error)), error)

    def inject_text(self, text):
        """A user turn by text, as if spoken."""
        self.send(Command(inject_text=text))

    def say(self, text):
        """Words the assistant says."""
        self.send(Command(say=text))

    def select_choice(self, index):
        """The user picked the last reply's choice at `index` (from 0)."""
        self.send(Command(select_choice=index))

    def interrupt(self):
        """Stops the reply playing, like the user talking over it."""
        self.send(Command(interrupt=True))

    def set_param(self, name, value):
        """Sets a declared $session.<name> of the agent."""
        command = Command()
        command.set_session_param.name = name
        command.set_session_param.value.CopyFrom(_value_message(value))
        self.send(command)

    def fire_trigger(self, name, payload=None):
        """Fires the agent's app_event triggers named `name`; payload (a dict or a Struct) is $trigger.payload."""
        command = Command()
        command.fire_trigger.name = name
        command.fire_trigger.payload.CopyFrom(_struct_message(payload))
        self.send(command)

    def set_context(self, context):
        """The app's state, a dict (or a Struct): what the agent's $context.* reads (and its
        context_change triggers watch), and {context} in the LLM's instructions. Each top-level key is replaced."""
        data = _struct_message(context).SerializeToString()
        error = ctypes.c_void_p()
        _check(_session_set_context(self._handle, data, len(data), _BINARY, ctypes.byref(error)), error)

    def set_network_available(self, available):
        _session_set_network(self._handle, 1 if available else 0)

    def reset_conversation(self):
        """Starts the conversation over: the LLM's history cleared, the agent at its start."""
        self.send(Command(reset_conversation=True))

    def push_to_talk(self, held):
        """The talk button held (True) or let go (False): PUSH_TO_TALK and HYBRID activation."""
        self.send(Command(push_to_talk=bool(held)))

    def set_follow_up_listen_ms(self, ms):
        """How long the assistant keeps listening after a reply; 0: not at all."""
        self.send(Command(follow_up_listen_ms=int(ms)))

    def set_entity_values(self, name, values):
        """A dynamic entity's values (the phone's contacts): vasdk.EntityValue messages, or dicts {"value", "spoken", "synonyms"}."""
        self.send(Command(set_entity_values=_entity_values(name, values)))

    def set_backchannel(self, backchannel):
        """Back-channel handling: a vasdk.Backchannel, or a dict of its fields; the fields given replace the session's."""
        if not isinstance(backchannel, Backchannel):
            backchannel = json_format.ParseDict(backchannel, Backchannel())
        self.send(Command(set_backchannel=backchannel))

    def enroll_speaker(self, speaker_id):
        """The next utterance enrolls speaker_id, replacing their voice print; a speaker_enrollment
        event says how it went. Needs providers.speaker_embedding in the config."""
        self.send(Command(enroll_speaker=speaker_id))

    def add_speaker(self, speaker_id, voice_print):
        """Restores a voice print (a list of floats) kept from speakers()."""
        self.send(Command(add_speaker=VoicePrint(speaker_id=speaker_id, embedding=list(voice_print))))

    def speakers(self):
        """The enrolled speakers' voice prints, {speaker_id: [floats]}, to keep across sessions."""
        length = ctypes.c_size_t()
        prints = events_pb2.VoicePrints.FromString(_take_bytes(_session_speakers(self._handle, _BINARY, ctypes.byref(length)), length))
        return {print_.speaker_id: list(print_.embedding) for print_ in prints.speakers}

    def on_context(self, function):
        """fn() -> dict: the app's state, asked for each time the agent or the LLM reads it; its keys
        win over set_context's. Before start(). Usable as a decorator."""
        def callback(result, _user):
            try:
                _result_set(result, _encode(json.dumps(function() or {})))
            except Exception as error:
                _report("on_context", error)
        _session_on_context(self._handle, self._keep(_CONTEXT(callback)), None)
        return function

    def add_processor(self, slot, function):
        """A processor of the app's at a slot, before start():
          AFTER_INPUT:         fn(pcm: bytes), the microphone's audio, to read
          BEFORE_OUTPUT:       fn(pcm: bytes) -> bytes or None, the reply's audio; bytes of the same length replace it
          AFTER_TRANSCRIPTION: fn(text) -> str or None, each final transcript
          BEFORE_SYNTHESIS:    fn(text) -> str or None, each part of a reply
        For text, None passes it on, a string replaces it, "" drops it."""
        if slot in (AFTER_INPUT, BEFORE_OUTPUT):
            def audio(pcm, samples, _rate, _user):
                try:
                    changed = function(_pcm_bytes(pcm, samples))
                    if slot == BEFORE_OUTPUT and changed is not None and len(changed) == samples * 2:
                        ctypes.memmove(pcm, bytes(changed), samples * 2)
                except Exception as error:
                    _report("audio processor", error)
            added = _session_add_audio_processor(self._handle, slot, self._keep(_AUDIO_PROCESSOR(audio)), None)
        else:
            def text(words, result, _user):
                try:
                    changed = function(words.decode("utf-8"))
                    if changed is not None:
                        _result_set(result, _encode(changed))
                except Exception as error:
                    _report("text processor", error)
            added = _session_add_text_processor(self._handle, slot, self._keep(_TEXT_PROCESSOR(text)), None)
        if not added:
            raise VasdkError(f"no processor added at slot {slot} (a slot of the other kind, or the session started)")
        return function

    def describe(self):
        """What the session runs: its providers, its LLM, its stages."""
        return _take(_session_describe(self._handle)) or ""

    def using_fallbacks(self):
        """True while the network is down and the local fallbacks speak and listen."""
        return bool(_session_using_fallbacks(self._handle))

    def next_scheduled_trigger(self):
        """When the agent's next schedule trigger is due, in milliseconds since the epoch; None for none."""
        due = _session_next_trigger(self._handle)
        return None if due < 0 else due

    def trigger_state(self):
        """What the agent's triggers have seen, as JSON: keep it to restore_trigger_state() after a restart."""
        return _take(_session_trigger_state(self._handle)) or ""

    def restore_trigger_state(self, state):
        _session_restore_triggers(self._handle, _encode(state))

    def snapshot(self):
        """Where the agent's conversation is, to start(resume=...) a later session there: a
        vasdk.ConversationSnapshot (its flow empty when there's nothing to resume). Store it with
        SerializeToString(), or json_format.MessageToJson()."""
        length = ctypes.c_size_t()
        snapshot = ConversationSnapshot()
        snapshot.ParseFromString(_take_bytes(_session_snapshot(self._handle, _BINARY, ctypes.byref(length)), length))
        return snapshot

    def _keep(self, callback):
        with self._lock:
            self._callbacks.append(callback)
        return callback
